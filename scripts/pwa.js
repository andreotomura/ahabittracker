/*
 * pwa.js — text assets for the PWA build target (manifest, service worker,
 * and the <head> snippets injected into the hosted index.html).
 *
 * Pure string builders so they can be unit-tested; `build.js pwa` writes them
 * next to the inlined single-file `index.html`.
 */
'use strict';

const NAME = 'AHA(bit) tracker';
const SHORT_NAME = 'AHA(bit)';
const THEME = '#6d5df6';
const BG_LIGHT = '#f4f5fb';

/** App-shell files the service worker precaches (must be real, same-origin). */
const ASSETS = [
  './index.html',
  './manifest.webmanifest',
  './icon-192.png',
  './icon-512.png',
  './icon-maskable-512.png',
];

function manifest() {
  return `${JSON.stringify(
    {
      name: NAME,
      short_name: SHORT_NAME,
      description:
        'A beautiful, local-first habit tracker. Single-file, offline, private — your data stays yours as JSON.',
      start_url: './',
      scope: './',
      display: 'standalone',
      orientation: 'portrait',
      background_color: BG_LIGHT,
      theme_color: THEME,
      icons: [
        { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
        { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
      ],
    },
    null,
    2,
  )}\n`;
}

/**
 * Offline app-shell service worker. `version` is derived from the built HTML,
 * so any content change produces a new SW byte-stream, which makes browsers
 * install it and refresh the cache.
 */
function serviceWorker(version) {
  return `/* AHA(bit) tracker service worker — generated by build.js (version ${version}). */
'use strict';

const CACHE = 'ahabit-${version}';
const ASSETS = ${JSON.stringify(ASSETS)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  if (new URL(req.url).origin !== self.location.origin) return;

  // Navigations: network first, fall back to the cached app shell (offline).
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put('./index.html', copy));
          }
          return res;
        })
        .catch(() => caches.match('./index.html')),
    );
    return;
  }

  // Static assets: cache-first, then fill the cache from the network.
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
}

/** Injected where `<!--PWA-->` sits in src/index.html (head). */
const PWA_HEAD = `  <link rel="manifest" href="manifest.webmanifest">
  <link rel="apple-touch-icon" href="icon-192.png">
  <meta name="apple-mobile-web-app-capable" content="yes">
  <meta name="apple-mobile-web-app-title" content="${SHORT_NAME}">
  <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
  <script>
    // Register the service worker only over http(s) — file:// can't run one.
    if ('serviceWorker' in navigator && location.protocol.startsWith('http')) {
      window.addEventListener('load', function () {
        navigator.serviceWorker.register('sw.js').catch(function () {});
      });
    }
  </script>`;

module.exports = { manifest, serviceWorker, PWA_HEAD, ASSETS };
